CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    nickname VARCHAR(20),
    profile_image_url VARCHAR(500),
    gender VARCHAR(30),
    age_group VARCHAR(30),
    experience_period VARCHAR(30),
    ntrp NUMERIC(2, 1),
    tournament_history VARCHAR(500),
    same_gender_only BOOLEAN NOT NULL,
    activity_latitude NUMERIC(9, 6),
    activity_longitude NUMERIC(9, 6),
    activity_radius_km INTEGER,
    withdrawn_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_nickname UNIQUE (nickname),
    CONSTRAINT ck_users_active_profile CHECK (status <> 'ACTIVE' OR (nickname IS NOT NULL AND gender IS NOT NULL)),
    CONSTRAINT ck_users_ntrp CHECK (ntrp BETWEEN 1.0 AND 7.0),
    CONSTRAINT ck_users_activity_location CHECK ((activity_latitude IS NULL) = (activity_longitude IS NULL)),
    CONSTRAINT ck_users_activity_radius_km CHECK (activity_radius_km > 0)
);

CREATE TABLE user_preferred_match_type (
    user_id BIGINT NOT NULL,
    match_type VARCHAR(30) NOT NULL,
    CONSTRAINT pk_user_preferred_match_type PRIMARY KEY (user_id, match_type),
    CONSTRAINT fk_user_preferred_match_type_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_preferred_time_slot (
    user_id BIGINT NOT NULL,
    time_slot VARCHAR(30) NOT NULL,
    CONSTRAINT pk_user_preferred_time_slot PRIMARY KEY (user_id, time_slot),
    CONSTRAINT fk_user_preferred_time_slot_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE social_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_social_account_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_social_account_provider_provider_user_id UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_social_account_user_id_provider UNIQUE (user_id, provider)
);

CREATE TABLE court (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    latitude NUMERIC(9, 6) NOT NULL,
    longitude NUMERIC(9, 6) NOT NULL,
    has_parking BOOLEAN NOT NULL,
    has_shower BOOLEAN NOT NULL,
    facility_notes TEXT,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_court_latitude_longitude ON court (latitude, longitude);

CREATE TABLE court_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL,
    registrant_user_id BIGINT NOT NULL,
    court_number VARCHAR(20) NOT NULL,
    starts_at TIMESTAMP(6) NOT NULL,
    ends_at TIMESTAMP(6) NOT NULL,
    rental_fee INTEGER NOT NULL,
    evidence_file_key VARCHAR(500) NOT NULL,
    status VARCHAR(30) NOT NULL,
    rejection_reason VARCHAR(500),
    reviewed_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_court_slot_court FOREIGN KEY (court_id) REFERENCES court (id),
    CONSTRAINT fk_court_slot_registrant_user FOREIGN KEY (registrant_user_id) REFERENCES users (id),
    CONSTRAINT ck_court_slot_time_range CHECK (ends_at > starts_at),
    CONSTRAINT ck_court_slot_rental_fee CHECK (rental_fee >= 0),
    CONSTRAINT ex_court_slot_overlap EXCLUDE USING gist (
        court_id WITH =,
        court_number WITH =,
        tsrange(starts_at, ends_at) WITH &&
    ) WHERE (status <> 'REJECTED')
);

CREATE INDEX idx_court_slot_registrant_user_id ON court_slot (registrant_user_id);
CREATE INDEX idx_court_slot_starts_at ON court_slot (starts_at);

CREATE TABLE match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_slot_id BIGINT NOT NULL,
    host_user_id BIGINT NOT NULL,
    match_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    male_recruit_count INTEGER NOT NULL,
    female_recruit_count INTEGER NOT NULL,
    min_ntrp NUMERIC(2, 1),
    max_ntrp NUMERIC(2, 1),
    participation_fee INTEGER NOT NULL,
    recruitment_deadline TIMESTAMP(6) NOT NULL,
    confirmed_at TIMESTAMP(6),
    completed_at TIMESTAMP(6),
    canceled_at TIMESTAMP(6),
    cancel_reason VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_match_court_slot_id UNIQUE (court_slot_id),
    CONSTRAINT fk_match_court_slot FOREIGN KEY (court_slot_id) REFERENCES court_slot (id),
    CONSTRAINT fk_match_host_user FOREIGN KEY (host_user_id) REFERENCES users (id),
    CONSTRAINT ck_match_recruit_count CHECK (
        male_recruit_count >= 0
        AND female_recruit_count >= 0
        AND 1 + male_recruit_count + female_recruit_count BETWEEN 2 AND 6
    ),
    CONSTRAINT ck_match_min_ntrp CHECK (min_ntrp BETWEEN 1.0 AND 7.0),
    CONSTRAINT ck_match_max_ntrp CHECK (max_ntrp BETWEEN 1.0 AND 7.0),
    CONSTRAINT ck_match_ntrp_range CHECK (min_ntrp <= max_ntrp),
    CONSTRAINT ck_match_participation_fee CHECK (participation_fee >= 0)
);

CREATE INDEX idx_match_host_user_id ON match (host_user_id);
CREATE INDEX idx_match_status_recruitment_deadline ON match (status, recruitment_deadline);

CREATE TABLE match_preferred_age_group (
    match_id BIGINT NOT NULL,
    age_group VARCHAR(30) NOT NULL,
    CONSTRAINT pk_match_preferred_age_group PRIMARY KEY (match_id, age_group),
    CONSTRAINT fk_match_preferred_age_group_match FOREIGN KEY (match_id) REFERENCES match (id) ON DELETE CASCADE
);

CREATE TABLE match_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    applicant_user_id BIGINT NOT NULL,
    applicant_gender VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    reject_reason VARCHAR(30),
    cancel_reason VARCHAR(500),
    refund_policy_agreed_at TIMESTAMP(6) NOT NULL,
    accepted_at TIMESTAMP(6),
    payment_due_at TIMESTAMP(6),
    canceled_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_match_application_match FOREIGN KEY (match_id) REFERENCES match (id),
    CONSTRAINT fk_match_application_applicant_user FOREIGN KEY (applicant_user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX uk_match_application_active ON match_application (match_id, applicant_user_id)
    WHERE status IN ('PENDING', 'PAYMENT_PENDING', 'CONFIRMED');
CREATE INDEX idx_match_application_match_id_status ON match_application (match_id, status);
CREATE INDEX idx_match_application_applicant_user_id_status ON match_application (applicant_user_id, status);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_application_id BIGINT NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    payment_key VARCHAR(200),
    status VARCHAR(30) NOT NULL,
    amount INTEGER NOT NULL,
    balance_amount INTEGER NOT NULL,
    method VARCHAR(50),
    approved_at TIMESTAMP(6),
    processing_started_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_payment_match_application FOREIGN KEY (match_application_id) REFERENCES match_application (id),
    CONSTRAINT uk_payment_order_id UNIQUE (order_id),
    CONSTRAINT uk_payment_payment_key UNIQUE (payment_key),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_balance_amount CHECK (balance_amount BETWEEN 0 AND amount)
);

CREATE UNIQUE INDEX uk_payment_active_match_application ON payment (match_application_id)
    WHERE status NOT IN ('FAILED', 'EXPIRED');

CREATE TABLE payment_refund (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    idempotency_key VARCHAR(300) NOT NULL,
    amount INTEGER NOT NULL,
    reason VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    transaction_key VARCHAR(200),
    canceled_at TIMESTAMP(6),
    last_requested_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_payment_refund_payment FOREIGN KEY (payment_id) REFERENCES payment (id),
    CONSTRAINT uk_payment_refund_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_payment_refund_amount CHECK (amount > 0)
);

CREATE UNIQUE INDEX uk_payment_refund_pending_payment ON payment_refund (payment_id)
    WHERE status IN ('REQUESTED', 'UNKNOWN');
CREATE INDEX idx_payment_refund_payment_id ON payment_refund (payment_id);

CREATE TABLE settlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    amount INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    settled_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_settlement_match FOREIGN KEY (match_id) REFERENCES match (id),
    CONSTRAINT uk_settlement_match_id UNIQUE (match_id),
    CONSTRAINT ck_settlement_amount CHECK (amount >= 0)
);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL,
    match_id BIGINT,
    type VARCHAR(30) NOT NULL,
    title VARCHAR(100) NOT NULL,
    body VARCHAR(500) NOT NULL,
    dedupe_key VARCHAR(200),
    read_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_notification_recipient_user FOREIGN KEY (recipient_user_id) REFERENCES users (id),
    CONSTRAINT fk_notification_match FOREIGN KEY (match_id) REFERENCES match (id),
    CONSTRAINT uk_notification_dedupe_key UNIQUE (dedupe_key)
);

CREATE INDEX idx_notification_recipient_user_id_created_at ON notification (recipient_user_id, created_at);
